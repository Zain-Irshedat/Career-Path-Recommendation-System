import numpy as np
from imblearn.over_sampling import SMOTE
from sklearn.model_selection import train_test_split
from sklearn.ensemble import RandomForestClassifier

# ---------------------------------------------------------
# 1. Handling Class Imbalance (SMOTE)
# ---------------------------------------------------------
# Since the dataset is small (~6 samples per career), we use Synthetic Minority 
# Over-sampling Technique (SMOTE) to generate synthetic candidate profiles 
# and ensure the model doesn't become biased towards majority classes.

